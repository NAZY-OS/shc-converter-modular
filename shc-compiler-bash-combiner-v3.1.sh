#!/usr/bin/env bash

## compile_with_sourced_improved.sh - Pure Bash implementation# Detects source and . commands reliably in modular scripts
## Features:
# - Handles nested source commands
# - Preserves script structure
# - Avoids duplicate includes# - Works with relative/absolute paths
